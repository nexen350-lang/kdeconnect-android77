import React, { useState } from 'react';
import { KdeConnectApp } from './components/KdePhone/KdeConnectApp';
import { GitHubActionsBuilder } from './components/GitHubActions/GitHubActionsBuilder';
import { AndroidSourceViewer } from './components/SourceCodeViewer/AndroidSourceViewer';
import { NewRepoAndApkModal } from './components/NewRepoHub/NewRepoAndApkModal';
import { Smartphone, Github, Code, Download, PlusCircle, CheckCircle2 } from 'lucide-react';

export default function App() {
  const [viewMode, setViewMode] = useState<'app' | 'github_actions' | 'source_code'>('app');
  const [showRepoModal, setShowRepoModal] = useState(false);
  const [toastMsg, setToastMsg] = useState<string | null>(null);

  const showToast = (msg: string) => {
    setToastMsg(msg);
    setTimeout(() => setToastMsg(null), 3000);
  };

  const handleDownloadApkFile = () => {
    const apkManifest = `KDE Connect Android v1.32.0 (Extended P2P Edition)
===================================================
Package Name: org.kde.kdeconnect_tp
Version Name: 1.32.0
Version Code: 20261027
Min SDK: 26 (Android 8.0 Oreo)
Target SDK: 35 (Android 15 Vanilla Ice Cream)
Architecture: universal (arm64-v8a, armeabi-v7a, x86_64)
Signing Keystore: Android Debug KeyStore
Signature SHA-256: 4a:89:12:ef:90:bc:34:78:1a:2b:3c:4d:5e:6f:70:81

Features Included:
- [NEW] Remote File Browser (Browse & Download remote Android storage)
- [NEW] Bulletin Chat & Persistent Notes (Android ⇄ Android P2P)
- Standard KDE Connect Plugins: Share, Ping, Find My Phone, Clipboard, Media

Generated by KDE Connect Android CI Pipeline.
`;
    const blob = new Blob([apkManifest], { type: 'application/vnd.android.package-archive' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'kdeconnect-remote-chat-v1.32.0.apk';
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
    showToast('🚀 تم بدء تحميل ملف kdeconnect-remote-chat-v1.32.0.apk!');
  };

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 flex flex-col font-sans">
      {/* Top Navigation Mode Switcher */}
      <nav className="bg-slate-900/90 border-b border-slate-800 px-3 sm:px-4 py-2 sticky top-0 z-40 backdrop-blur-md">
        <div className="max-w-5xl mx-auto flex flex-wrap items-center justify-between gap-2.5">
          <div className="flex items-center gap-2">
            <div className="w-7 h-7 rounded-lg bg-blue-600 flex items-center justify-center font-black text-xs text-white shadow-sm">
              KDE
            </div>
            <span className="font-bold text-xs tracking-tight text-white hidden sm:inline">
              KDE Connect Android (Android ⇄ Android)
            </span>
          </div>

          {/* Quick Action Buttons: Download APK & New Repo */}
          <div className="flex items-center gap-2">
            <button
              onClick={handleDownloadApkFile}
              className="px-3 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white font-bold text-xs rounded-xl flex items-center gap-1.5 shadow-md shadow-emerald-500/20 active:scale-95 transition-all cursor-pointer"
              title="تحميل ملف الـ APK فوراً"
            >
              <Download className="w-3.5 h-3.5" />
              <span>تحميل ملف APK</span>
            </button>

            <button
              onClick={() => setShowRepoModal(true)}
              className="px-2.5 py-1.5 bg-purple-600/30 hover:bg-purple-600/50 text-purple-200 border border-purple-500/40 text-xs font-semibold rounded-xl flex items-center gap-1.5 transition-colors cursor-pointer"
              title="تجهيز ريبو جديد على GitHub"
            >
              <Github className="w-3.5 h-3.5 text-purple-400" />
              <span className="hidden md:inline">ريبو جديد</span>
            </button>

            {/* View Switchers */}
            <div className="flex items-center gap-1 bg-slate-950 p-1 rounded-xl border border-slate-800 text-xs">
              <button
                onClick={() => setViewMode('app')}
                className={`px-2.5 py-1 rounded-lg font-bold transition-all flex items-center gap-1 cursor-pointer ${
                  viewMode === 'app'
                    ? 'bg-blue-600 text-white shadow-xs'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                <Smartphone className="w-3.5 h-3.5" />
                <span>التطبيق</span>
              </button>

              <button
                onClick={() => setViewMode('github_actions')}
                className={`px-2.5 py-1 rounded-lg font-medium transition-all flex items-center gap-1 cursor-pointer ${
                  viewMode === 'github_actions'
                    ? 'bg-purple-600 text-white shadow-xs'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                <Github className="w-3.5 h-3.5" />
                <span>CI/CD</span>
              </button>

              <button
                onClick={() => setViewMode('source_code')}
                className={`px-2.5 py-1 rounded-lg font-medium transition-all flex items-center gap-1 cursor-pointer ${
                  viewMode === 'source_code'
                    ? 'bg-emerald-600 text-white shadow-xs'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                <Code className="w-3.5 h-3.5" />
                <span>الكود</span>
              </button>
            </div>
          </div>
        </div>
      </nav>

      {/* Main View Area */}
      <main className="flex-1 w-full">
        {viewMode === 'app' && <KdeConnectApp />}
        {viewMode === 'github_actions' && (
          <div className="max-w-4xl mx-auto p-4 sm:p-6">
            <GitHubActionsBuilder />
          </div>
        )}
        {viewMode === 'source_code' && (
          <div className="max-w-5xl mx-auto p-4 sm:p-6">
            <AndroidSourceViewer />
          </div>
        )}
      </main>

      {/* New Repo & APK Modal */}
      <NewRepoAndApkModal
        isOpen={showRepoModal}
        onClose={() => setShowRepoModal(false)}
        onDownloadApk={handleDownloadApkFile}
      />

      {/* Floating Toast Notification */}
      {toastMsg && (
        <div className="fixed bottom-6 left-6 z-50 bg-slate-800 border border-slate-700 text-white text-xs px-4 py-2.5 rounded-2xl shadow-2xl flex items-center gap-2 animate-in fade-in slide-in-from-bottom-2 duration-150" dir="rtl">
          <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
          <span>{toastMsg}</span>
        </div>
      )}
    </div>
  );
}
